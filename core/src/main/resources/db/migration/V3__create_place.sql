CREATE TABLE places (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id        BIGINT         NOT NULL,
    name               VARCHAR(100)   NOT NULL,
    thumbnail_url      TEXT           NOT NULL,
    address            VARCHAR(200)   NOT NULL,
    lat                NUMERIC(10, 7) NOT NULL,
    lng                NUMERIC(10, 7) NOT NULL,
    sns_url            TEXT,
    homepage_url       TEXT,
    schedule_type      VARCHAR(10)    NOT NULL,
    start_date         DATE,
    end_date           DATE,
    status             VARCHAR(20)    NOT NULL,
    status_change_type VARCHAR(10)    NOT NULL,
    created_at         TIMESTAMP(6)   NOT NULL,
    updated_at         TIMESTAMP(6)   NOT NULL,

    CONSTRAINT fk_places_category
        FOREIGN KEY (category_id) REFERENCES categories (id),

    CONSTRAINT ck_places_schedule_type
        CHECK (schedule_type IN ('PERIOD', 'ALWAYS')),
    CONSTRAINT ck_places_status
        CHECK (status IN ('SCHEDULED', 'ACTIVE', 'INACTIVE', 'PENDING')),
    CONSTRAINT ck_places_status_change_type
        CHECK (status_change_type IN ('AUTO', 'MANUAL')),

    CONSTRAINT ck_places_lat  CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT ck_places_lng  CHECK (lng BETWEEN -180 AND 180),
    CONSTRAINT ck_places_date CHECK (start_date <= end_date),
    -- 기간제(PERIOD)는 시작일/종료일 필수, 상시(ALWAYS)는 둘 다 없음
    CONSTRAINT ck_places_schedule CHECK (
        (schedule_type = 'PERIOD' AND start_date IS NOT NULL AND end_date IS NOT NULL)
            OR (schedule_type = 'ALWAYS' AND start_date IS NULL AND end_date IS NULL)
    )
);

CREATE INDEX idx_places_category ON places (category_id);

CREATE TABLE operating_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id    BIGINT       NOT NULL,
    day_of_week VARCHAR(3)   NOT NULL,
    is_open     BOOLEAN      NOT NULL,
    open_time   TIME,
    close_time  TIME,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,

    CONSTRAINT fk_operating_hours_place
        FOREIGN KEY (place_id) REFERENCES places (id) ON DELETE CASCADE,
    CONSTRAINT ck_operating_hours_day
        CHECK (day_of_week IN ('MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN')),
    CONSTRAINT uq_operating_hours_place_day UNIQUE (place_id, day_of_week),
    CONSTRAINT ck_operating_hours_time CHECK (
        (is_open = TRUE  AND open_time IS NOT NULL AND close_time IS NOT NULL)
            OR (is_open = FALSE AND open_time IS NULL     AND close_time IS NULL)
    )
);

CREATE TABLE keywords (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(30)  NOT NULL UNIQUE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE place_keywords (
    place_id   BIGINT NOT NULL,
    keyword_id BIGINT NOT NULL,

    CONSTRAINT pk_place_keywords PRIMARY KEY (place_id, keyword_id),
    CONSTRAINT fk_place_keywords_place
        FOREIGN KEY (place_id)   REFERENCES places (id)   ON DELETE CASCADE,
    CONSTRAINT fk_place_keywords_keyword
        FOREIGN KEY (keyword_id) REFERENCES keywords (id) ON DELETE CASCADE
);

CREATE INDEX idx_place_keywords_keyword ON place_keywords (keyword_id);
