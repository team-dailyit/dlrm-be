CREATE TABLE neighborhoods (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name       VARCHAR(20) NOT NULL UNIQUE,
    lat         NUMERIC(10, 7) NOT NULL,
    lng         NUMERIC(10, 7) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,

    CONSTRAINT ck_neighborhoods_lat  CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT ck_neighborhoods_lng  CHECK (lng BETWEEN -180 AND 180)
);

ALTER TABLE places
    ADD COLUMN neighborhood_id BIGINT NOT NULL,
    ADD CONSTRAINT fk_places_neighborhood
        FOREIGN KEY (neighborhood_id) REFERENCES neighborhoods (id);

CREATE INDEX idx_places_neighborhood ON places (neighborhood_id);
